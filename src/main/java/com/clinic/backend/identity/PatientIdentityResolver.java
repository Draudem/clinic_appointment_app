package com.clinic.backend.identity;

import java.time.LocalDate;
import java.util.Optional;

/**
 * ПОР идентификации пациента.
 *
 * Почему это отдельный этап. Регламент (раздел 3.5) требует идентифицировать
 * пациента перед ЛЮБЫМ действием с записями, и требует, чтобы первым данные
 * называл сам пациент. Пока личность не установлена, ассистент не имеет права
 * произнести ни ФИО, ни дату рождения, ни сведения о записях — даже если
 * что-то «похожее» уже известно.
 *
 * Смена реализации (БД клиники, МИС «Инфоклиника», ЕПГУ) не затрагивает
 * сценарий: он видит только этот интерфейс.
 */
public interface PatientIdentityResolver {

    /** Человекочитаемое имя реализации — попадает в диагностику. */
    String name();

    /**
     * Ищет пациента по логину. Нужен для HTTP-входа: там личность уже
     * подтверждена авторизацией, но сценарию нужны ФИО и дата рождения,
     * чтобы обратиться по имени.
     */
    Optional<PatientIdentity> findByLogin(String login);

    /**
     * Ищет пациента по фамилии, имени, отчеству и дате рождения.
     *
     * Основной путь для телефона. Возвращает пусто, если пациент не найден
     * или найден более чем один: оба случая по регламенту ведут к переводу
     * (R-07), а не к догадке.
     */
    Optional<PatientIdentity> findByFioAndBirthDate(String fio, LocalDate birthDate);

    /** Поиск по номеру телефона — только как дополнительный признак. */
    Optional<PatientIdentity> findByPhone(String phone);

    /** Ищет по одной фамилии — чтобы переспросить, а не сказать «не найдено». */
    Optional<PatientIdentity> findByLastName(String lastName);
}