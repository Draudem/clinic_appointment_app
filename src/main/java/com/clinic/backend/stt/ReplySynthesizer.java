package com.clinic.backend.stt;

/**
 * Порт синтеза речи: текст -> PCM для отправки в AudioSocket.
 *
 * Каждая реализация работает на своей частоте (Piper, например, выдаёт 22050 Гц),
 * поэтому частота — часть контракта: вызывающий код приводит звук к 8 кГц сам.
 *
 * Замена движка (Silero, облачный сервис) = другая реализация этого интерфейса,
 * AudioSocket-сервер при этом не меняется.
 */
public interface ReplySynthesizer {

    /**
     * @param text текст ответа
     * @return PCM в диапазоне [-1..1] на частоте {@link #sampleRate()} сэмплов/сек;
     *         null или пустой массив — отправить тишину
     */
    float[] synthesize(String text);

    /** Частота выхода синтеза, Гц. */
    int sampleRate();

    /** Умеет ли синтезировать (false у заглушки и если модель не загрузилась). */
    boolean available();

    /** Имя движка для диагностики. */
    String name();
}