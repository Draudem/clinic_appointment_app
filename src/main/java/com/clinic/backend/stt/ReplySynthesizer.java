package com.clinic.backend.stt;

/**
 * Порт синтеза речи: текст -> PCM 16 кГц для отправки в Asterisk.
 *
 * Сейчас реализация-заглушка ({@link SilentReplySynthesizer}): возвращает тишину
 * нужной длительности, чтобы Asterisk держал соединение и не рвал вызов, пока
 * распознанный текст забирают по HTTP.
 *
 * Задел сделан намеренно: AudioSocket умеет передавать только АУДИО, текст в сокет
 * отдать нельзя. Поэтому голосовой ответ возможен только через синтез. Когда появится
 * TTS-модель (она есть в той же библиотеке sherpa-onnx), достаточно добавить вторую
 * реализацию этого интерфейса и переключить бин — AudioSocket-сервер не меняется.
 */
public interface ReplySynthesizer {

    /**
     * @param text текст ответа
     * @return PCM 16 кГц моно [-1..1]; null или пустой массив — отправить тишину
     */
    float[] synthesize(String text);

    /** Умеет ли синтезировать (false у заглушки). */
    boolean available();

    /** Имя движка для диагностики. */
    String name();
}