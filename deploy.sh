#!/usr/bin/env bash
# ЕДИНЫЙ скрипт деплоя бэкенда: сборка из исходников -> копирование на сервер -> запуск.
#
# Запускать С ЛОКАЛЬНОЙ машины из корня бэкенда:
#   ./deploy.sh            # собрать из исходников, задеплоить и запустить на сервере
#   ./deploy.sh down       # остановить и полностью очистить наш стек на сервере
#
# Адрес сервера/каталог можно переопределить:
#   SERVER=root@1.2.3.4 REMOTE_DIR=/opt/clinic ./deploy.sh
#
# Вся логика — в deploy/deploy-local.sh; этот файл просто точка входа из корня.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
exec "$SCRIPT_DIR/deploy/deploy-local.sh" "$@"
